import json
import uuid
from pathlib import Path
from datetime import datetime, timezone
from typing import Dict, Any, Optional, List
from dataclasses import dataclass, asdict

from src.guardrails.patch_validator import PatchValidatorGuardrail
from src.guardrails.filesystem import FileSystemGuardrail
from src.guardrails.command_safety import CommandSafetyGuardrail
from src.guardrails.audit import AuditLogger
from src.guardrails.secrets import redact_secrets
from src.config import settings


@dataclass
class FixProposal:
    fix_id: str
    status: str  # PROPOSED, APPROVED, REJECTED, APPLIED, ROLLED_BACK
    problem_description: str
    target_file: str
    original_sha256: str
    new_sha256: str
    diff: str
    diff_lines: int
    rationale: str
    created_at: str
    updated_at: str
    approved_by: Optional[str] = None
    approval_notes: Optional[str] = None
    rejection_reason: Optional[str] = None
    backup_path: Optional[str] = None
    run_id: Optional[str] = None
    new_content: Optional[str] = None  # retained for application

    def to_dict(self, include_content: bool = False) -> Dict[str, Any]:
        data = asdict(self)
        if not include_content:
            data.pop("new_content", None)
        return data


class FixManager:
    """
    Manages the lifecycle of proposed code patches:
    PROPOSED -> (APPROVED | REJECTED) -> APPLIED -> ROLLED_BACK.
    
    CRITICAL SECURITY CONTROL:
    Generating a patch and applying it are separate operations.
    Applying a patch independently verifies:
      1. Explicit human approval status.
      2. Exact target file matching.
      3. SHA-256 staleness verification.
      4. Automatic backup creation before write.
    """

    def __init__(
        self,
        storage_path: Optional[Path] = None,
        audit_logger: Optional[AuditLogger] = None
    ):
        self.storage_path = storage_path or (settings.PROJECT_ROOT / "data" / "fixes.json")
        self.storage_path.parent.mkdir(parents=True, exist_ok=True)
        self.audit_logger = audit_logger or AuditLogger()
        self.patch_validator = PatchValidatorGuardrail()
        self.fs_guard = FileSystemGuardrail()
        self.cmd_guard = CommandSafetyGuardrail()
        self._fixes: Dict[str, FixProposal] = {}
        self._load_fixes()

    def _load_fixes(self):
        """Loads fixes from persistent JSON file."""
        if self.storage_path.exists():
            try:
                data = json.loads(self.storage_path.read_text(encoding="utf-8"))
                for fix_id, fix_dict in data.items():
                    self._fixes[fix_id] = FixProposal(**fix_dict)
            except Exception as exc:
                print(f"[FIX MANAGER ERROR]: Failed to load fixes ({exc})")

    def _save_fixes(self):
        """Persists fixes to storage file."""
        try:
            serialized = {
                fix_id: asdict(fix)
                for fix_id, fix in self._fixes.items()
            }
            self.storage_path.write_text(json.dumps(serialized, indent=2), encoding="utf-8")
        except Exception as exc:
            print(f"[FIX MANAGER ERROR]: Failed to save fixes ({exc})")

    def propose_fix(
        self,
        target_file: str,
        new_content: str,
        problem_description: str,
        rationale: str = "Automated bugfix generated by Codebase Debugging Agent",
        run_id: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Validates proposed content and creates a PROPOSED fix without modifying any files.
        """
        # Validate path and diff boundaries
        is_valid, msg, diff_text = self.patch_validator.validate_patch(
            target_path=target_file,
            new_content=new_content
        )

        if not is_valid:
            return {
                "success": False,
                "message": msg,
                "fix_id": None
            }

        # Resolve target path and get current hash
        _, resolved_path, _ = self.fs_guard.sanitize_and_resolve(target_file)
        original_content = resolved_path.read_text(encoding="utf-8") if resolved_path.exists() else ""
        orig_sha = self.patch_validator.compute_sha256(original_content)
        new_sha = self.patch_validator.compute_sha256(new_content)

        fix_id = f"fix_{uuid.uuid4().hex[:8]}"
        now = datetime.now(timezone.utc).isoformat()

        proposal = FixProposal(
            fix_id=fix_id,
            status="PROPOSED",
            problem_description=problem_description,
            target_file=str(resolved_path.relative_to(settings.PROJECT_ROOT)).replace("\\", "/"),
            original_sha256=orig_sha,
            new_sha256=new_sha,
            diff=diff_text,
            diff_lines=len(diff_text.splitlines()),
            rationale=rationale,
            created_at=now,
            updated_at=now,
            run_id=run_id,
            new_content=new_content
        )

        self._fixes[fix_id] = proposal
        self._save_fixes()

        # Audit log creation
        self.audit_logger.log_event(
            event_type="FIX_PROPOSED",
            target_file=proposal.target_file,
            rationale=rationale,
            approval_status="PENDING_HUMAN_APPROVAL",
            diff_summary={"diff_lines": proposal.diff_lines},
            extra_details={"fix_id": fix_id, "problem": problem_description}
        )

        return {
            "success": True,
            "message": "Fix proposed successfully. Awaiting explicit human approval before applying.",
            "fix": proposal.to_dict()
        }

    def get_fix(self, fix_id: str) -> Optional[Dict[str, Any]]:
        """Retrieves fix details by ID."""
        fix = self._fixes.get(fix_id)
        return fix.to_dict() if fix else None

    def get_diff(self, fix_id: str) -> Optional[Dict[str, Any]]:
        """Retrieves exact diff for review."""
        fix = self._fixes.get(fix_id)
        if not fix:
            return None
        return {
            "fix_id": fix.fix_id,
            "target_file": fix.target_file,
            "status": fix.status,
            "diff": fix.diff,
            "diff_lines": fix.diff_lines,
            "original_sha256": fix.original_sha256,
            "new_sha256": fix.new_sha256
        }

    def approve_fix(
        self,
        fix_id: str,
        approved_by: str = "human_user",
        notes: Optional[str] = None
    ) -> Dict[str, Any]:
        """Explicitly approves the exact proposed patch."""
        fix = self._fixes.get(fix_id)
        if not fix:
            return {"success": False, "message": f"Fix '{fix_id}' not found."}

        if fix.status in ("APPLIED", "ROLLED_BACK"):
            return {
                "success": False,
                "message": f"Fix '{fix_id}' is already {fix.status} and cannot be approved again."
            }

        fix.status = "APPROVED"
        fix.approved_by = approved_by
        fix.approval_notes = notes
        fix.updated_at = datetime.now(timezone.utc).isoformat()
        self._save_fixes()

        self.audit_logger.log_event(
            event_type="FIX_APPROVED",
            target_file=fix.target_file,
            rationale=fix.rationale,
            approval_status="APPROVED",
            diff_summary={"diff_lines": fix.diff_lines},
            extra_details={"fix_id": fix_id, "approved_by": approved_by, "notes": notes}
        )

        return {
            "success": True,
            "message": f"Fix '{fix_id}' approved. Ready to apply.",
            "fix": fix.to_dict()
        }

    def reject_fix(
        self,
        fix_id: str,
        reason: Optional[str] = "Rejected by human reviewer"
    ) -> Dict[str, Any]:
        """Rejects a proposed patch."""
        fix = self._fixes.get(fix_id)
        if not fix:
            return {"success": False, "message": f"Fix '{fix_id}' not found."}

        fix.status = "REJECTED"
        fix.rejection_reason = reason
        fix.updated_at = datetime.now(timezone.utc).isoformat()
        self._save_fixes()

        self.audit_logger.log_event(
            event_type="FIX_REJECTED",
            target_file=fix.target_file,
            rationale=fix.rationale,
            approval_status="REJECTED",
            diff_summary={"diff_lines": fix.diff_lines},
            extra_details={"fix_id": fix_id, "reason": reason}
        )

        return {
            "success": True,
            "message": f"Fix '{fix_id}' has been rejected.",
            "fix": fix.to_dict()
        }

    def apply_fix(
        self,
        fix_id: str,
        run_tests_command: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Applies an approved patch after safety checks, staleness verification,
        and automatic backup creation.
        """
        fix = self._fixes.get(fix_id)
        if not fix:
            return {"success": False, "message": f"Fix '{fix_id}' not found."}

        # 1. INDEPENDENT SECURITY CONTROL: Check approval status
        if fix.status != "APPROVED":
            return {
                "success": False,
                "status": "APPROVAL_REQUIRED",
                "message": f"Security Violation: Fix '{fix_id}' cannot be applied because its status is '{fix.status}' (must be explicitly 'APPROVED')."
            }

        # 2. Check path safety
        _, resolved_path, msg = self.fs_guard.sanitize_and_resolve(fix.target_file)
        is_safe_write, write_msg = self.fs_guard.is_safe_write_path(resolved_path)
        if not is_safe_write:
            return {"success": False, "message": f"Security Guardrail: {write_msg}"}

        # 3. Staleness Check (Target file content must match expected hash)
        current_content = resolved_path.read_text(encoding="utf-8") if resolved_path.exists() else ""
        current_sha = self.patch_validator.compute_sha256(current_content)
        if current_sha != fix.original_sha256:
            fix.status = "PROPOSED"  # Require re-approval!
            fix.updated_at = datetime.now(timezone.utc).isoformat()
            self._save_fixes()
            return {
                "success": False,
                "status": "STALE_PATCH",
                "message": (
                    f"Staleness Violation: Target file '{fix.target_file}' was modified on disk since the patch was generated. "
                    "Approval has been revoked for safety. Please review and re-propose."
                )
            }

        # 4. Create automatic timestamped backup
        backup_path = self.patch_validator.create_backup(resolved_path)
        fix.backup_path = str(backup_path) if backup_path else None

        # 5. Apply the patch
        try:
            resolved_path.write_text(fix.new_content or "", encoding="utf-8")
        except Exception as exc:
            return {"success": False, "message": f"Failed to write patch to file: {exc}"}

        # 6. Optional automated regression testing
        test_success = True
        test_output = ""
        if run_tests_command:
            is_cmd_allowed, _, rationale = self.cmd_guard.is_command_allowed(run_tests_command)
            if not is_cmd_allowed:
                # Revert immediately if illegal command was attempted
                if backup_path:
                    self.patch_validator.rollback(backup_path, resolved_path)
                return {
                    "success": False,
                    "message": f"Patch aborted: Test command disallowed by CommandSafetyGuardrail ({rationale})."
                }

            cmd_ok, code, stdout, stderr = self.cmd_guard.execute_safe_command(run_tests_command)
            test_success = cmd_ok
            test_output = stdout + "\n" + stderr

            if not cmd_ok:
                # Automatically rollback if tests failed
                if backup_path:
                    self.patch_validator.rollback(backup_path, resolved_path)
                fix.status = "PROPOSED"
                self._save_fixes()
                return {
                    "success": False,
                    "message": f"Patch rolled back: Automated tests failed with exit code {code}.",
                    "test_output": test_output
                }

        fix.status = "APPLIED"
        fix.updated_at = datetime.now(timezone.utc).isoformat()
        self._save_fixes()

        self.audit_logger.log_event(
            event_type="FIX_APPLIED",
            target_file=fix.target_file,
            rationale=fix.rationale,
            approval_status="APPROVED",
            diff_summary={"diff_lines": fix.diff_lines},
            tests_executed=run_tests_command,
            test_outcome="PASSED" if test_success else "FAILED",
            extra_details={"fix_id": fix_id, "backup": fix.backup_path}
        )

        return {
            "success": True,
            "message": f"Fix '{fix_id}' applied successfully to '{fix.target_file}'.",
            "fix": fix.to_dict(),
            "test_output": test_output if run_tests_command else None
        }

    def rollback_fix(self, fix_id: str) -> Dict[str, Any]:
        """Attempts to safely revert an applied patch using its backup."""
        fix = self._fixes.get(fix_id)
        if not fix:
            return {"success": False, "message": f"Fix '{fix_id}' not found."}

        if fix.status != "APPLIED":
            return {
                "success": False,
                "message": f"Fix '{fix_id}' cannot be rolled back because status is '{fix.status}' (must be 'APPLIED')."
            }

        if not fix.backup_path or not Path(fix.backup_path).exists():
            return {
                "success": False,
                "message": f"Cannot rollback fix '{fix_id}': Backup file not found."
            }

        _, resolved_path, _ = self.fs_guard.sanitize_and_resolve(fix.target_file)
        success = self.patch_validator.rollback(fix.backup_path, resolved_path)
        if not success:
            return {"success": False, "message": "Rollback failed during file copy."}

        fix.status = "ROLLED_BACK"
        fix.updated_at = datetime.now(timezone.utc).isoformat()
        self._save_fixes()

        self.audit_logger.log_event(
            event_type="FIX_ROLLED_BACK",
            target_file=fix.target_file,
            rationale=f"Rollback of fix {fix_id}",
            approval_status="APPROVED",
            extra_details={"fix_id": fix_id, "restored_from": fix.backup_path}
        )

        return {
            "success": True,
            "message": f"Fix '{fix_id}' successfully rolled back. Original file content restored.",
            "fix": fix.to_dict()
        }


# Global fix manager instance
fix_manager = FixManager()
