from pydantic import BaseModel, Field
from typing import List, Dict, Any, Optional
from datetime import datetime


# ===========================================================================
# Stage 1: Core API Schemas
# ===========================================================================

class HealthResponse(BaseModel):
    status: str = "ok"
    service: str = "codebase-debugging-agent"
    timestamp: str


class ReadyResponse(BaseModel):
    status: str
    components: Dict[str, bool]
    details: Dict[str, Any]


class DebugQueryRequest(BaseModel):
    question: str = Field(..., description="Debugging question or problem statement.")
    thread_id: str = Field(default="default_session", description="Session ID for multi-turn persistence.")
    max_retries: int = Field(default=2, ge=1, le=5, description="Maximum AST validation fix attempts.")


class DebugQueryResponse(BaseModel):
    question: str
    final_answer: str
    investigated_files: List[str]
    active_symbols: List[str]
    context_verified: bool
    context_confidence: float
    fix_valid: bool
    error: Optional[str] = None


class SearchRequest(BaseModel):
    query: str = Field(..., description="Search query describing class, function, or concept.")
    top_k: int = Field(default=5, ge=1, le=20, description="Maximum number of code chunks to retrieve.")
    search_type: str = Field(default="all", description="Search target: 'code', 'doc', or 'all'.")


class SearchResponse(BaseModel):
    query: str
    total_results: int
    results: List[Dict[str, Any]]


class DebugInvestigateRequest(BaseModel):
    bug_description: str = Field(..., description="Detailed description of the bug or issue.")
    error_trace: Optional[str] = Field(default=None, description="Optional stack trace or compiler error message.")
    suspected_files: Optional[List[str]] = Field(default=None, description="Optional list of suspected file paths.")
    thread_id: Optional[str] = Field(default=None, description="Optional session thread ID.")


class DebugInvestigateResponse(BaseModel):
    bug_description: str
    diagnosis: str
    supporting_references: List[Dict[str, Any]]
    investigated_files: List[str]
    active_symbols: List[str]
    context_verified: bool
    error: Optional[str] = None


# ===========================================================================
# Stage 2: Repository Indexing Schemas
# ===========================================================================

class IndexRequest(BaseModel):
    target_path: str = Field(default=".", description="Root directory of target repository to index.")
    reset_index: bool = Field(default=True, description="Whether to clear existing ChromaDB collection.")
    async_mode: bool = Field(default=True, description="Run indexing as a background worker thread.")


class IndexResponse(BaseModel):
    success: bool
    message: str
    status: Dict[str, Any]


class IndexStatusResponse(BaseModel):
    is_indexing: bool
    status: str
    target_path: Optional[str] = None
    files_count: int
    chunks_count: int
    records_stored: int
    started_at: Optional[str] = None
    completed_at: Optional[str] = None
    last_indexed_at: Optional[str] = None
    error: Optional[str] = None


# ===========================================================================
# Stage 3: LangGraph Workflow & Fix Proposal Schemas
# ===========================================================================

class AgentRunResponse(BaseModel):
    run_id: str
    status: str
    question: str
    final_answer: str
    step_count: int
    retry_count: int
    investigated_files: List[str]
    active_symbols: List[str]
    fix_valid: bool
    context_verified: bool
    error: Optional[str] = None


class AgentRunEventsResponse(BaseModel):
    run_id: str
    events_count: int
    events: List[Dict[str, Any]]


class FixProposeRequest(BaseModel):
    problem_description: str = Field(..., description="Description of the bug this patch resolves.")
    target_file: str = Field(..., description="Relative path of file to be modified (e.g. 'src/foo.py').")
    new_content: Optional[str] = Field(default=None, description="Full replacement content for the target file. If omitted, generated automatically.")
    rationale: Optional[str] = Field(default="Automated bugfix generated by Codebase Debugging Agent", description="Justification for changes.")
    run_id: Optional[str] = Field(default=None, description="Associated agent run/session ID.")


class FixResponse(BaseModel):
    success: bool
    message: str
    fix: Optional[Dict[str, Any]] = None


class FixDiffResponse(BaseModel):
    fix_id: str
    target_file: str
    status: str
    diff: str
    diff_lines: int
    original_sha256: str
    new_sha256: str


# ===========================================================================
# Stage 4: Approval & Safe Changes Schemas
# ===========================================================================

class FixApproveRequest(BaseModel):
    approved_by: str = Field(default="human_user", description="Name or identifier of the human approver.")
    notes: Optional[str] = Field(default=None, description="Optional reviewer approval remarks.")


class FixRejectRequest(BaseModel):
    reason: Optional[str] = Field(default="Rejected by reviewer", description="Explanation for rejecting the patch.")


class FixApplyRequest(BaseModel):
    run_tests_command: Optional[str] = Field(
        default=None,
        description="Optional safe test command (e.g. 'pytest testings/test_guardrails.py') to execute post-application."
    )


class FixApplyResponse(BaseModel):
    success: bool
    message: str
    fix: Optional[Dict[str, Any]] = None
    test_output: Optional[str] = None


class FixRollbackResponse(BaseModel):
    success: bool
    message: str
    fix: Optional[Dict[str, Any]] = None


# ===========================================================================
# Stage 5: Testing, Workflow, & Monitoring Schemas
# ===========================================================================

class TestRunRequest(BaseModel):
    test_command: str = Field(
        default="pytest testings/test_guardrails.py",
        description="Approved test command from safe allowlist."
    )
    timeout_seconds: int = Field(default=45, ge=5, le=180, description="Execution timeout limit.")


class TestRunResponse(BaseModel):
    test_run_id: str
    command: str
    success: bool
    returncode: int
    stdout: str
    stderr: str
    duration_seconds: float


class AuditLogsResponse(BaseModel):
    total_logs: int
    count: int
    logs: List[Dict[str, Any]]


class EvaluationResponse(BaseModel):
    report_source: str
    summary: Dict[str, Any]
    detailed_samples: List[Dict[str, Any]]